--For every customer, calculate:
--Customer ID
--Customer name
--Number of orders placed
--Total amount paid through successful payments only
--Display only customers whose successful payment amount is greater than ₹50,000.
--Sort customers from highest to lowest successful payment amount.

select
  c.CustomerID,
  c.Name,
  count(distinct o.OrderID) as no_of_orders,
  sum(p.Amount) as total_paid
from `e1.customers` as c
inner join `e1.orders` as o
  on c.CustomerID = o.CustomerID
inner join `e1.payments` as p
  on p.OrderID = o.OrderID
where p.Status = "success"
group by c.CustomerID,c.Name
having sum(p.Amount) > 50000
order by total_paid desc


--Find the top 10 products by total sales value.
--Display:
--ProductID --> product
--ProductName --> product
--CategoryName --> category
--SupplierName --> supplier
--Number of times the product appeared in order items -->order_items
--Total quantity sold--> order_items
--Total sales value --> order_items
--Average selling price --> order_items
--Only include products where the total sales value is greater than ₹1,00,000.

select
  p.ProductID,
  p.ProductName,
  c.categoryName,
  s.SupplierName,
  count(oi.OrderID) as no_of_prds,
  sum(oi.Quantity) as total_quantity,
  sum(oi.Total) as total_sales_value,
  avg(oi.SellingPrice) as avg_selling_price
from `e1.products` as p
inner join `e1.categories` as c
on p.CategoryID = c.categoryID
inner join `e1.suppliers` as s
on s.SupplierID = p.SupplierID
inner join `e1.order_items` as oi
 on oi.ProductID = p.ProductID
group by
  p.ProductID,
  p.ProductName,
  c.categoryName,
  s.SupplierName
having sum(oi.Total) > 100000
order by total_sales_value desc
limit 10


--Consider only products having an MRP greater than ₹20,000.
--For every category, calculate:
--CategoryID --> category
--CategoryName --> category
--Number of qualifying products --> products
--Average MRP of qualifying products --> products
--Maximum MRP --> products
--Minimum MRP --> products
--Display only categories having more than 2 qualifying products.
--Sort by average MRP from highest to lowest.

select
  c.categoryID,
  c.categoryName,
  count(p.ProductID) as no_of_products,
  round(avg(p.MRP),2) as avg_mrp,
  max(p.MRP) as max_mrp,
  min(p.MRP) as min_mrp
from `e1.products` as p
inner join `e1.categories` as c
 on p.CategoryID = c.categoryID
where MRP > 20000
group by 
c.categoryID,
c.categoryName
having count(p.ProductID) > 2
order by avg_mrp desc


