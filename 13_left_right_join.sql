--For every supplier, calculate:
--SupplierID --> supplier
--SupplierName --> supplier
--Number of products supplied --> product
--Average MRP of their products --> product
--Total sales generated by their products --> order_items
--Total quantity sold --> order_items
--Include suppliers even if their products have never been sold.--> priority to suppliers
--For suppliers with no sales, display the sales and quantity as 0.
--Sort suppliers by total sales from highest to lowest.

select
  s.SupplierID,
  s.SupplierName,
  count(distinct p.ProductID) as no_of_products,
  avg(p.MRP) as avg_mrp,
  coalesce(sum(oi.Total),0) as total_sales,
  coalesce(sum(oi.Quantity),0) as total_qnts
from `e1.suppliers` as s
left join `e1.products` as p    
  on s.SupplierID = p.SupplierID
left join `e1.order_items` as oi
  on p.ProductID = oi.ProductID
group by
s.SupplierID,
s.SupplierName
order by total_sales desc




